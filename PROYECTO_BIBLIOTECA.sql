-- Tabla USUARIOS 
CREATE TABLE USUARIOS(
    ID_USUARIO INT PRIMARY KEY,
    NOMBRE NVARCHAR(100) NOT NULL,
    APELLIDOS NVARCHAR(100) NOT NULL,
    TELEFONO NVARCHAR(20),
    DOCUMENTO NVARCHAR(20) NOT NULL
);

-- Tabla GENEROS 
CREATE TABLE GENEROS (
    CODIGO_GENERO INT PRIMARY KEY,
    NOMBRE_GENERO NVARCHAR(100) NOT NULL
);

-- Tabla AUTORES 
CREATE TABLE AUTORES (
    ID_AUTOR INT PRIMARY KEY,
    NOMBRE_AUTOR NVARCHAR(100) NOT NULL
);

-- Tabla LIBROS 
CREATE TABLE LIBROS(
    CODIGO_LIBRO INT PRIMARY KEY,
    TITULO_LIBRO NVARCHAR(MAX) NOT NULL,
    ANIO INT,
    CODIGO_GENERO INT,
    ID_AUTOR INT,
    FOREIGN KEY (ID_AUTOR) REFERENCES AUTORES(ID_AUTOR),
    FOREIGN KEY (CODIGO_GENERO) REFERENCES GENEROS(CODIGO_GENERO)
);

-- Tabla PRESTAMOS
CREATE TABLE PRESTAMOS(
    CODIGO_PRESTAMO INT PRIMARY KEY,
    ID_USUARIO INT,
    FECHA_PRESTAMO DATE NOT NULL,
    FECHA_DEVOLUCION DATE,
    FOREIGN KEY(ID_USUARIO) REFERENCES USUARIOS(ID_USUARIO)
);

-- Tabla DETALLE_PRESTAMOS
CREATE TABLE DETALLE_PRESTAMOS(
    ID_DETALLE INT PRIMARY KEY,
    CODIGO_PRESTAMO INT,
    CODIGO_LIBRO INT,
    FOREIGN KEY(CODIGO_PRESTAMO) REFERENCES PRESTAMOS(CODIGO_PRESTAMO),
    FOREIGN KEY(CODIGO_LIBRO) REFERENCES LIBROS(CODIGO_LIBRO)
);

