--CONSULTAS
--FUNCIONES AGREGADOS 
--TOTAL DE USUARIOS 
SELECT COUNT (*) AS TOTAL_DE_USUARIOS
FROM USUARIOS;
--LIBROS TOTALES EXISTENTES
SELECT COUNT (*) AS LIBROS_EXISTENTES
FROM LIBROS;
--ANTIGüEDAD Y ACTUALIDAD DE LOS LIBROS
SELECT
 MIN (ANIO) AS LIBRO_AÑO_ANTIGUO,
 MAX (ANIO) AS LIBRO_AÑO_RECIENTE
FROM LIBROS;
--PROMEDIO DE LIBROS DESPUES DE 1900
SELECT AVG (ANIO) AS PROMEDIO_LIBROS_DESPUES
FROM LIBROS
WHERE ANIO >1900;

--JOINS(INNER)
--TITULO Y NOMBRE DE AUTOR 
SELECT L.TITULO_LIBRO, A.NOMBRE_AUTOR
FROM LIBROS L
INNER JOIN AUTORES A ON L.ID_AUTOR = A.ID_AUTOR;
-- PRESTAMOS USUARIOS
SELECT P.CODIGO_PRESTAMO, U.NOMBRE, U.APELLIDOS
FROM PRESTAMOS P 
INNER JOIN USUARIOS U ON P.ID_USUARIO = U.ID_USUARIO;
--LIBRO PRESTADO EN CADA DETALLE
SELECT DP.ID_DETALLE, L.TITULO_LIBRO
FROM DETALLE_PRESTAMOS DP
INNER JOIN LIBROS L ON DP.CODIGO_LIBRO = L.CODIGO_LIBRO;

--GROUP BY 
--LIBROS POR GENERO 
SELECT G.NOMBRE_GENERO, COUNT(*) AS TOTAL_LIBROS
FROM LIBROS L
INNER JOIN GENEROS G ON L.CODIGO_GENERO = G.CODIGO_GENERO
GROUP  BY G.NOMBRE_GENERO;
--PRESTAMOS POR USUARIO 
SELECT U.NOMBRE, U.APELLIDOS, COUNT (*) AS TOTAL_PRESTAMOS
FROM PRESTAMOS P 
INNER JOIN USUARIOS U ON P.ID_USUARIO = U.ID_USUARIO
GROUP BY U.NOMBRE, U.APELLIDOS;


